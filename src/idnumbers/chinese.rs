/// Chinese resident identity numbers: a location, the birthday `yyyyMMdd`, three random digits and an ISO 7064
/// check character (`X` for 10).
#[derive(Debug, Clone, Copy, Default)]
pub struct ChineseIdNumber;

impl ChineseIdNumber {
    /// `getValidSsn(faker)` (deprecated upstream): `generateValid(faker)`.
    pub fn get_valid_ssn(&self, faker: &Faker) -> Result<String> {
        self.generate_valid(faker)
    }

    /// `idNumber(res)`: the 17 characters followed by their check character.
    pub fn id_number(res: &[char]) -> String {
        const WEIGHTS: [i32; 17] = [7, 9, 10, 5, 8, 4, 2, 1, 6, 3, 7, 9, 10, 5, 8, 4, 2];
        let count: i32 = res.iter().zip(WEIGHTS).map(|(c, w)| (*c as i32 - '0' as i32) * w).sum();
        let count = (12 - count % 11) % 11;
        let text: String = res.iter().collect();
        if count == 10 { format!("{text}X") } else { format!("{text}{count}") }
    }
}

fn digit_char(value: i32) -> char {
    char::from_u32(('0' as i32 + value) as u32).unwrap_or('\u{FFFD}')
}

fn fill_birthday(res: &mut Vec<char>, birthday: LocalDate) {
    let (year, month, day) = (birthday.year(), birthday.month_value() as i32, birthday.day_of_month() as i32);
    for value in [year / 1000, year % 1000 / 100, year % 100 / 10, year % 10, month / 10, month % 10, day / 10, day % 10] {
        res.push(digit_char(value));
    }
}

impl IdNumberGenerator for ChineseIdNumber {
    fn country_code(&self) -> &'static str {
        "CN"
    }

    fn generate_valid_for(&self, faker: &Faker, request: &IdNumberRequest) -> Result<PersonIdNumber> {
        let birth_date = birthday(faker, request)?;
        let random = faker.random();
        // `faker.options().option(LOCATIONS)`.
        let index = random.next_int_bounded(LOCATION_COUNT as i32)? as usize;
        let mut res: Vec<char> = LOCATIONS[index * 6..index * 6 + 6].chars().collect();
        fill_birthday(&mut res, birth_date);
        for _ in 0..3 {
            res.push(digit_char(random.next_int_bounded(10)?));
        }
        let id_number = ChineseIdNumber::id_number(&res);
        Ok(PersonIdNumber { id_number, birth_date, gender: gender(faker, request) })
    }

    fn generate_invalid(&self, faker: &Faker) -> Result<String> {
        Ok(format!("{}42", self.generate_valid(faker)?))
    }
}
