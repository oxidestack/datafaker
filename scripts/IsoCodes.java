// Writes src/providers/iso_codes.rs: java.util.Locale.getISOLanguages() and getISOCountries() of the running JDK, in
// its order, which Nation.isoLanguage()/isoCountry() draw from. Run by scripts/iso-codes.sh.
import java.util.Locale;

public class IsoCodes {
  public static void main(String[] a) {
    StringBuilder sb = new StringBuilder();
    sb.append("//! `Locale.getISOLanguages()` and `Locale.getISOCountries()` of JDK ")
      .append(System.getProperty("java.version"))
      .append(", in the JDK's order.\n//! Generated by `scripts/iso-codes.sh`; do not edit.\n\n");
    array(sb, "ISO_LANGUAGES", Locale.getISOLanguages());
    sb.append('\n');
    array(sb, "ISO_COUNTRIES", Locale.getISOCountries());
    System.out.print(sb);
  }

  static void array(StringBuilder sb, String name, String[] values) {
    sb.append("pub(crate) const ").append(name).append(": &[&str] = &[\n");
    for (int i = 0; i < values.length; i += 16) {
      sb.append("   ");
      for (int j = i; j < Math.min(i + 16, values.length); j++) sb.append(" \"").append(values[j]).append("\",");
      sb.append('\n');
    }
    sb.append("];\n");
  }
}
