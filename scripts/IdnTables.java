// Generates src/idn_tables.rs (IDNA2003 nameprep as java.net.IDN applies it, on its Unicode 3.2 tables) and
// tests/vectors/idn.tsv (IDN.toASCII results) from the running JDK: scripts/idn-tables.sh. Every table is read
// back from IDN.toASCII itself, one code point at a time:
//   UNASSIGNED  code points refused as unassigned (RFC 3454 table A.1, flag 0)
//   PROHIBITED  code points whose nameprep output holds a prohibited code point (tables C.1.2, C.2.2, C.3-C.9)
//   MAP         code points whose nameprep output (B.1, B.2, NFKC) is not the code point itself; read by decoding
//               the Punycode of IDN.toASCII(cp, ALLOW_UNASSIGNED)
//   RAND_AL     code points of bidi class R or AL (D.1): cp + "a" breaks the bidi rule
//   L           code points of bidi class L (D.2): "א" + cp + "א" breaks the bidi rule
import java.io.*;
import java.net.IDN;
import java.nio.charset.StandardCharsets;
import java.util.*;

public class IdnTables {
  static String ascii(String s, int flags) {
    try { return IDN.toASCII(s, flags); } catch (IllegalArgumentException e) { return "ERR " + e.getMessage(); }
  }

  static boolean bidiError(String r) { return r.startsWith("ERR ") && r.contains("BiDi"); }

  public static void main(String[] a) throws Exception {
    String rs = a[0], tsv = a[1];
    int max = 0x10FFFF;
    BitSet unassigned = new BitSet(), prohibited = new BitSet(), randAl = new BitSet(), l = new BitSet();
    TreeMap<Integer, String> map = new TreeMap<>();
    List<String> oddities = new ArrayList<>();
    for (int cp = 0x80; cp <= max; cp++) {
      if (cp >= 0xD800 && cp <= 0xDFFF) continue;
      String s = new String(Character.toChars(cp));
      String r0 = ascii(s, 0);
      if (r0.startsWith("ERR ") && r0.contains("unassigned")) { unassigned.set(cp); continue; }
      String r = ascii(s, IDN.ALLOW_UNASSIGNED);
      String out;
      if (r.startsWith("ERR ")) {
        if (r.contains("prohibited")) { prohibited.set(cp); continue; }
        if (r.contains("Empty label")) { out = ""; }
        else if (r.contains("BiDi")) {
          // An output that starts or ends with a mark (FB1D -> U+05D9 U+05B4): read it between two alefs.
          String wrapped = ascii("\u05D0" + s + "\u05D0", IDN.ALLOW_UNASSIGNED);
          String decoded = wrapped.startsWith("xn--") ? IDN.toUnicode(wrapped, IDN.ALLOW_UNASSIGNED) : "";
          if (decoded.length() < 2 || decoded.charAt(0) != '\u05D0' || decoded.charAt(decoded.length() - 1) != '\u05D0') {
            oddities.add(Integer.toHexString(cp) + " " + r);
            continue;
          }
          out = decoded.substring(1, decoded.length() - 1);
        }
        else { oddities.add(Integer.toHexString(cp) + " " + r); continue; }
      } else if (r.startsWith("xn--")) {
        out = IDN.toUnicode(r, IDN.ALLOW_UNASSIGNED);
      } else {
        out = r;
      }
      if (!out.equals(s)) map.put(cp, out);
      else {
        if (bidiError(ascii(s + "a", IDN.ALLOW_UNASSIGNED))) randAl.set(cp);
        if (bidiError(ascii("א" + s + "א", IDN.ALLOW_UNASSIGNED))) l.set(cp);
      }
    }
    // Every code point a mapping produces must be one the tables classify as itself.
    for (Map.Entry<Integer, String> e : map.entrySet()) {
      e.getValue().codePoints().forEach(c -> {
        if (c >= 0x80 && (map.containsKey(c) || unassigned.get(c) || prohibited.get(c))) oddities.add("output " + Integer.toHexString(c) + " of " + Integer.toHexString(e.getKey()));
      });
    }
    for (String o : oddities) System.err.println("odd: " + o);
    try (PrintWriter w = new PrintWriter(new OutputStreamWriter(new FileOutputStream(rs), StandardCharsets.UTF_8))) {
      w.println("// Generated by scripts/idn-tables.sh from " + System.getProperty("java.vm.name") + " " + System.getProperty("java.version") + "'s java.net.IDN; do not edit.");
      w.println("// Nameprep (RFC 3491) on Unicode 3.2 as the JDK applies it, read back one code point at a time.");
      w.println();
      ranges(w, "UNASSIGNED", unassigned);
      ranges(w, "PROHIBITED", prohibited);
      ranges(w, "RAND_AL", randAl);
      ranges(w, "L", l);
      w.println("/// Code points whose nameprep output is not themselves, with that output (empty: mapped to nothing).");
      w.println("pub(crate) static MAP: &[(u32, &str)] = &[");
      StringBuilder line = new StringBuilder("   ");
      for (Map.Entry<Integer, String> e : map.entrySet()) {
        String item = " (0x" + Integer.toHexString(e.getKey()).toUpperCase() + ", \"" + escape(e.getValue()) + "\"),";
        if (line.length() + item.length() > 120) { w.println(line); line = new StringBuilder("   "); }
        line.append(item);
      }
      if (line.length() > 3) w.println(line);
      w.println("];");
    }
    // Vectors: single code points at a stride, and labels mixing them with ASCII, Hebrew and Latin letters.
    Random random = new Random(3491);
    try (PrintWriter w = new PrintWriter(new OutputStreamWriter(new FileOutputStream(tsv), StandardCharsets.UTF_8))) {
      w.println("# IDN.toASCII(input) (flag 0) from " + System.getProperty("java.vm.name") + " " + System.getProperty("java.version") + ": input TAB result (ERR <message>); scripts/idn-tables.sh");
      List<String> inputs = new ArrayList<>(List.of("Ⱥ", "Ⱥbby.com", "AȺ", "bücher", "BÜCHER.de", "ß", "ς", "a­b", "אaא",
        "aא", "אב", "العربية", "�", "a�b", "　", "a　b", "\u007F",
        "é", "가", "각", "Ä", "⾆8", "陋", "xn--abc", "Xn--ü", "", ".", "a.", "a..b", "。",
        "münchen。de", "Å", "Ω", "ﬁ", "½", "①", "İ", "ẞ", "ͅ", "ﷺ", "۝", "̀"));
      for (int cp = 0x80; cp <= 0x2FFFF; cp += 37) {
        if (cp >= 0xD800 && cp <= 0xDFFF) continue;
        inputs.add(new String(Character.toChars(cp)));
      }
      for (int i = 0; i < 3000; i++) {
        StringBuilder sb = new StringBuilder();
        int n = 1 + random.nextInt(4);
        for (int k = 0; k < n; k++) {
          int kind = random.nextInt(6);
          int cp = switch (kind) {
            case 0 -> 'a' + random.nextInt(26);
            case 1 -> 0x5D0 + random.nextInt(27);
            case 2 -> 0x300 + random.nextInt(0x70);
            case 3 -> 0xAC00 + random.nextInt(0x2BA4);
            default -> 0x80 + random.nextInt(0xFF80);
          };
          if (cp >= 0xD800 && cp <= 0xDFFF) cp = 'z';
          sb.appendCodePoint(cp);
        }
        inputs.add(sb.toString());
      }
      for (String in : inputs) {
        w.println(escape(in) + "\t" + escape(ascii(in, 0)));
      }
    }
  }

  static void ranges(PrintWriter w, String name, BitSet set) {
    w.println("pub(crate) static " + name + ": &[(u32, u32)] = &[");
    StringBuilder line = new StringBuilder("   ");
    for (int i = set.nextSetBit(0); i >= 0; ) {
      int end = set.nextClearBit(i) - 1;
      String item = " (0x" + Integer.toHexString(i).toUpperCase() + ", 0x" + Integer.toHexString(end).toUpperCase() + "),";
      if (line.length() + item.length() > 120) { w.println(line); line = new StringBuilder("   "); }
      line.append(item);
      i = set.nextSetBit(end + 1);
    }
    if (line.length() > 3) w.println(line);
    w.println("];");
    w.println();
  }

  // Rust string escapes for the table; the TSV uses the same ones (backslash, tab, newline, quote, and braced
  // hex escapes for controls and invisible code points).
  static String escape(String s) {
    StringBuilder sb = new StringBuilder();
    s.codePoints().forEach(c -> {
      if (c == '\\') sb.append("\\\\");
      else if (c == '"') sb.append("\\\"");
      else if (c == '\t') sb.append("\\t");
      else if (c == '\n') sb.append("\\n");
      else if (c < 0x20 || c == 0x7F || (c >= 0x80 && c < 0xA0) || Character.getType(c) == Character.FORMAT
        || Character.getType(c) == Character.PRIVATE_USE || Character.getType(c) == Character.UNASSIGNED
        || Character.getType(c) == Character.LINE_SEPARATOR || Character.getType(c) == Character.PARAGRAPH_SEPARATOR
        || Character.getType(c) == Character.NON_SPACING_MARK && sb.length() == 0)
        sb.append("\\u{").append(Integer.toHexString(c).toUpperCase()).append("}");
      else sb.appendCodePoint(c);
    });
    return sb.toString();
  }
}
