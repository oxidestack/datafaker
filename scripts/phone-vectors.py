#!/usr/bin/env python3
"""Writes the rows of tests/vectors/phone_numbers.tsv (seeds and calls; scripts/record.sh then asks Datafaker 2.7.0
with libphonenumber 9.0.41): the four generating PhoneNumber methods on three seeds for every locale of
Locality.allSupportedLocales() (read as PhoneNumberValidityFinderTest.createLocale reads them), every locale of
PhoneNumberTest.locales(), and the language-only locales of PhoneNumberValidityFinderTest.detectsCountryByLanguage,
plus locales whose country libphonenumber does not know (an exception row)."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CALLS = ["cellPhone", "cellPhoneInternational", "phoneNumberNational", "phoneNumberInternational"]
SEEDS = [1, 42, -7]


def supported_locales():
    src = (ROOT / "src/providers/locality.rs").read_text(encoding="utf-8")
    body = src[src.index("pub const LOCALES"):]
    body = body[:body.index("];")]
    out = []
    for tag in re.findall(r'"([^"]+)"', body):
        if tag.startswith("_"):
            out.append(("en", tag[1:].upper()))
        elif "-" in tag:
            language, country = tag.split("-")[:2]
            out.append((language, country))
        else:
            out.append((tag, ""))
    return out


TEST_LOCALES = [
    ("en", "US"), ("en", "GB"), ("en", "AU"), ("en", "CA"), ("en", "MS"), ("en", "NG"), ("en", "NZ"), ("et", "EE"),
    ("bg", "BG"), ("by", "BY"), ("ca", "CA"), ("cs", "CZ"), ("de", "DE"), ("de", "AT"), ("de", "CH"), ("en", "IN"),
    ("en", "NP"), ("en", "PK"), ("hu", "HU"), ("fi", "FI"), ("ko", "KR"), ("ja", "JP"), ("lv", "LV"), ("mk", "MK"),
    ("ca", "IT"), ("nl", "NL"), ("pl", "PL"), ("pt", "PT"), ("ro", "MD"), ("sq", "AL"), ("zh", "CN"), ("zh", "TW"),
    ("uk", "UA"), ("tr", "TR"), ("en", "SG"), ("en", "PH"), ("en", "UG"), ("en", "ZA"), ("sv", "SE"), ("th", "TH"),
    ("sk", "SK"), ("ru", "RU"), ("pt", "BR"), ("es", "AR"), ("es", "MX"), ("es", "PY"), ("es", "ES"), ("fr", "CA"),
    ("fr", "FR"), ("he", "IL"), ("hr", "HR"), ("hy", "AM"), ("id", "ID"), ("nb", "NO"), ("no", "NO"), ("da", "DK"),
    ("vi", "VI"), ("fr", "CH"), ("en", "IE"),
]
LANGUAGES = ["en", "hy", "uk", "ja", "fa", "ka", "sq", "cs", "be", "he", "ta", "et", "el", "eu", "ca", "cy", "ga",
             "is", "bs", "ar", "hi", "zh", "am", "sw", "af", "bn", "gl", "km", "ko", "mo", "ug", "ur", "test"]
UNKNOWN = [("en", "IND"), ("en", "XX"), ("ca", "CAT"), ("en", "NEP"), ("en", "PAK"), ("en", "BORK"), ("nb", ""),
           ("pt", "")]


def main():
    seen = []
    for loc in supported_locales() + TEST_LOCALES + [(l, "") for l in LANGUAGES] + UNKNOWN:
        if loc not in seen:
            seen.append(loc)
    lines = ["# Generated by scripts/phone-vectors.py; recorded from Datafaker 2.7.0 with libphonenumber 9.0.41 by",
             "# scripts/record.sh."]
    for language, country in seen:
        root = f"faker_{language}_{country}" if country else f"faker_{language}"
        for seed in SEEDS:
            lines.append(f"{seed}\t" + ";".join(f"{root}.phoneNumber().{c}()" for c in CALLS))
    (ROOT / "tests/vectors/phone_numbers.tsv").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
