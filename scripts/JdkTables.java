// Writes src/providers/jdk_tables.rs: what Datafaker reads from the running JDK's locale data, for the providers that
// read it. Run by scripts/jdk-tables.sh.
//   LOCALITY_DISPLAY_NAMES  Locality.displayName(): for each of Locality's tags (in its order), the root-locale
//                           display language and country of Locale.forLanguageTag(tag)
//   CURRENCIES              Money: Currency.getAvailableCurrencies() (a HashSet of objects with identity hash codes,
//                           so its order changes between JVM runs; here sorted by code), each as code, numeric code
//                           string, display name and symbol in the default locale en_US
//   NUMBER_SYMBOLS          new DecimalFormatSymbols(locale) (zero digit, decimal separator, and the negative prefix a
//                           DecimalFormat with it prints) of every available locale without script or variant, where
//                           it differs from en's
import java.util.*;

public class JdkTables {
  public static void main(String[] a) throws Exception {
    Locale.setDefault(Locale.US);
    StringBuilder sb = new StringBuilder();
    sb.append("//! Locale data of JDK ").append(System.getProperty("java.version"))
      .append(" that Datafaker reads (see scripts/JdkTables.java).\n//! Generated by `scripts/jdk-tables.sh`; do not edit.\n\n");
    var f = Class.forName("net.datafaker.providers.base.Locality").getDeclaredField("LOCALES");
    f.setAccessible(true);
    @SuppressWarnings("unchecked") List<String> tags = (List<String>) f.get(null);
    sb.append("/// `(tag, displayLanguage, displayCountry)` in `Locale.ROOT`.\n");
    sb.append("pub(crate) const LOCALITY_DISPLAY_NAMES: &[(&str, &str, &str)] = &[\n");
    for (String tag : tags) {
      Locale l = Locale.forLanguageTag(tag);
      sb.append("    (").append(q(tag)).append(", ").append(q(l.getDisplayLanguage(Locale.ROOT))).append(", ")
        .append(q(l.getDisplayCountry(Locale.ROOT))).append("),\n");
    }
    sb.append("];\n\n/// `Locale.ENGLISH.getDisplayLanguage(Locale.ROOT)`.\npub(crate) const ENGLISH_DISPLAY_LANGUAGE: &str = ")
      .append(q(Locale.ENGLISH.getDisplayLanguage(Locale.ROOT))).append(";\n\n");
    List<Currency> cs = new ArrayList<>(Currency.getAvailableCurrencies());
    cs.sort(Comparator.comparing(Currency::getCurrencyCode));
    sb.append("/// `(currencyCode, numericCodeAsString, displayName, symbol)`, sorted by code.\n");
    sb.append("pub(crate) const CURRENCIES: &[(&str, &str, &str, &str)] = &[\n");
    for (Currency c : cs) {
      sb.append("    (").append(q(c.getCurrencyCode())).append(", ").append(q(c.getNumericCodeAsString())).append(", ")
        .append(q(c.getDisplayName())).append(", ").append(q(c.getSymbol())).append("),\n");
    }
    sb.append("];\n\n");
    sb.append("/// `(language, country, zeroDigit, decimalSeparator, negativePrefix)` where `new DecimalFormatSymbols(locale)`\n")
      .append("/// differs from `0`, `.`, `-`; sorted. A locale missing here falls back to its language, then to `0`, `.`, `-`.\n");
    sb.append("pub(crate) const NUMBER_SYMBOLS: &[(&str, &str, char, char, &str)] = &[\n");
    List<Locale> ls = new ArrayList<>();
    for (Locale l : Locale.getAvailableLocales()) {
      if (l.getScript().isEmpty() && l.getVariant().isEmpty() && !l.getLanguage().isEmpty()) ls.add(l);
    }
    ls.sort(Comparator.comparing(Locale::toString));
    for (Locale l : ls) {
      var d = new java.text.DecimalFormatSymbols(l);
      String negative = new java.text.DecimalFormat("#0", d).format(-1);
      negative = negative.substring(0, negative.length() - 1);
      if (d.getZeroDigit() == '0' && d.getDecimalSeparator() == '.' && negative.equals("-")) continue;
      sb.append("    (").append(q(l.getLanguage())).append(", ").append(q(l.getCountry())).append(", ")
        .append(c(d.getZeroDigit())).append(", ").append(c(d.getDecimalSeparator())).append(", ").append(q(negative)).append("),\n");
    }
    sb.append("];\n");
    System.out.print(sb);
  }

  static String c(char ch) {
    String s = q(String.valueOf(ch));
    return "'" + s.substring(1, s.length() - 1).replace("\\\"", "\"") + "'";
  }

  static String q(String s) {
    StringBuilder sb = new StringBuilder("\"");
    for (char c : s.toCharArray()) {
      if (c == '"' || c == '\\') sb.append('\\').append(c);
      else if (c < 0x20 || c > 0x7e) sb.append(String.format("\\u{%x}", (int) c));
      else sb.append(c);
    }
    return sb.append('"').toString();
  }
}
